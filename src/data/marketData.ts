// Helper to generate realistic candlestick data for timeframes
function generateHistory(basePrice: number, changePercent: number): Record<string, any[]> {
  const timeframes = ['1D', '5D', '1M', '1Y', 'ALL'];
  const result: Record<string, any[]> = {};

  timeframes.forEach((tf) => {
    const pointsCount = tf === '1D' ? 24 : tf === '5D' ? 30 : tf === '1M' ? 30 : 40;
    const candles = [];
    let current = basePrice * (1 - (changePercent / 100) * (tf === '1D' ? 0.9 : 1.5));
    const volatility = basePrice * 0.008;

    for (let i = 0; i < pointsCount; i++) {
      const step = (Math.random() - 0.48) * volatility;
      const open = current;
      current = Math.max(open + step, 1);
      const close = current;
      const high = Math.max(open, close) + Math.random() * (volatility * 0.5);
      const low = Math.min(open, close) - Math.random() * (volatility * 0.5);
      const volume = Math.floor(Math.random() * 500000 + 100000);

      let timeLabel = '';
      if (tf === '1D') {
        const hour = 9 + Math.floor(i / 3);
        const min = (i % 3) * 20;
        timeLabel = `${hour.toString().padStart(2, '0')}:${min.toString().padStart(2, '0')}`;
      } else if (tf === '5D') {
        timeLabel = `Day ${Math.floor(i / 6) + 1}`;
      } else if (tf === '1M') {
        timeLabel = `Sep ${i + 1}`;
      } else {
        timeLabel = `M${(i % 12) + 1}`;
      }

      candles.push({
        time: timeLabel,
        open: parseFloat(open.toFixed(2)),
        high: parseFloat(high.toFixed(2)),
        low: parseFloat(low.toFixed(2)),
        close: parseFloat(close.toFixed(2)),
        volume,
      });
    }

    // Ensure the last close matches basePrice
    if (candles.length > 0) {
      candles[candles.length - 1].close = basePrice;
    }
    result[tf] = candles;
  });

  return result;
}

